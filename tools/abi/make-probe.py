#!/usr/bin/env python3
"""The ABI 1 probe (#139), generated from the frozen v0.1.0 headers.

ABI 1 was frozen at v0.1.0 (CLAUDE.md, ?zucrypt_c_api): within major version
1 nothing that v0.1.0 published may change its value, position or size.
tools/abi/v0.1.0/ holds that release's two headers, copied from the tag
(commit 5a43275). This script reads them and writes tools/abi/probe.c, a
program that prints one line per thing v0.1.0 published:

    enum   ZUC_ALG_SHA384 3          every enumerator's value
    macro  ZUC_INFO_REQUIRED_SIZE 24 every ZUC_/ZUCRYPT_ object-like macro
    field  zuc_info.random_backend 16 8     offset and size of each field
    field  zucrypt_api_v1.hash_update 104 8 of the two published structs

tools/ci/check-abi.sh compiles it twice, against the frozen headers and
against inst/include, and fails unless every line of the first output is in
the second. The names come from the old headers, so the probe asks only
about what v0.1.0 published; what was added since is free to be anything.

    python3 tools/abi/make-probe.py [--check]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OLD = os.path.join(ROOT, "tools", "abi", "v0.1.0")
OUT = os.path.join(ROOT, "tools", "abi", "probe.c")


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def enumerators(code):
    names = []
    for body in re.findall(r"typedef\s+enum\s*\{(.*?)\}\s*\w+\s*;", code, re.S):
        for m in re.finditer(r"\b(ZUC_[A-Z0-9_]+)\s*(?:=[^,}]*)?[,}]?", body):
            names.append(m.group(1))
    return names


def macros(code):
    names = []
    for m in re.finditer(r"^\s*#\s*define\s+((?:ZUC|ZUCRYPT)_[A-Z0-9_]+)(\(?)",
                         code, re.M):
        name, function_like = m.group(1), m.group(2)
        if function_like or name.endswith("_H"):
            continue
        names.append(name)
    return names


def fields(code, struct):
    m = re.search(r"typedef\s+struct\s*\{(.*?)\}\s*" + struct + r"\s*;",
                  code, re.S)
    if not m:
        sys.exit(f"no struct {struct}")
    out = []
    for decl in m.group(1).split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        fp = re.search(r"\(\s*\*\s*(\w+)\s*\)", decl)
        if fp:
            out.append(fp.group(1))
        else:
            out.append(re.findall(r"(\w+)\s*$", decl)[0])
    return out


def generate():
    core = strip_comments(open(os.path.join(OLD, "zucrypt.h")).read())
    table = strip_comments(open(os.path.join(OLD, "zucrypt-r.h")).read())
    enums = enumerators(core)
    defs = macros(core) + macros(table)
    info = fields(core, "zuc_info")
    api = fields(table, "zucrypt_api_v1")
    lines = [
        "/* Generated by tools/abi/make-probe.py from tools/abi/v0.1.0/ (#139).",
        " * Do not edit: re-run the generator. Compiled against the frozen",
        " * headers and against inst/include by tools/ci/check-abi.sh. */",
        "#include <stddef.h>",
        "#include <stdio.h>",
        "#include <zucrypt-r.h>",
        "",
        "#define ENUM(x) printf(\"enum  %s %ld\\n\", #x, (long) (x))",
        "#define MACRO(x) printf(\"macro %s %ld\\n\", #x, (long) (x))",
        "#define FIELD(s, f) printf(\"field %s.%s %lu %lu\\n\", #s, #f, \\",
        "    (unsigned long) offsetof(s, f), (unsigned long) sizeof(((s *) 0)->f))",
        "",
        "int main(void)",
        "{",
    ]
    lines += [f"    ENUM({n});" for n in enums]
    lines += [f"    MACRO({n});" for n in defs]
    lines += [f"    FIELD(zuc_info, {f});" for f in info]
    lines += [f"    FIELD(zucrypt_api_v1, {f});" for f in api]
    lines += ["    return 0;", "}", ""]
    counts = (len(enums), len(defs), len(info), len(api))
    return "\n".join(lines), counts


def main():
    text, (ne, nm, ni, na) = generate()
    print(f"{ne} enumerators, {nm} macros, {ni} zuc_info fields, "
          f"{na} zucrypt_api_v1 fields")
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("tools/abi/probe.c differs from the generator")
        print("make-probe --check: probe.c matches")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote tools/abi/probe.c")


if __name__ == "__main__":
    main()
